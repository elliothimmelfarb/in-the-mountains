// Bundle authored SVGs (docs/visual-overhaul/assets/*.svg + _meta.json) into a TS module
// the renderer imports: lib/render/asset-manifest.generated.ts (exports ASSETS: AssetDef[]).
//
//   node scripts/build-asset-manifest.mjs
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, basename } from "node:path";

const dir = "docs/visual-overhaul/assets";
const outTs = "lib/render/asset-manifest.generated.ts";

let meta = {};
const metaPath = join(dir, "_meta.json");
if (existsSync(metaPath)) meta = JSON.parse(readFileSync(metaPath, "utf8"));

const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".svg")).sort() : [];
const defs = files.map((f) => {
  const id = basename(f, ".svg");
  const svg = readFileSync(join(dir, f), "utf8").trim();
  const m = meta[id] || {};
  return {
    id,
    svg,
    anchor: m.anchor || [0.5, 0.5],
    footprint: m.footprint ?? null,
    rotating: !!m.rotating,
    family: m.family || null,
  };
});

const body =
  "// AUTO-GENERATED by scripts/build-asset-manifest.mjs — do not edit by hand.\n" +
  "// Source: docs/visual-overhaul/assets/*.svg (+ _meta.json).\n" +
  'import type { AssetDef } from "./sprites";\n\n' +
  "export const ASSETS: AssetDef[] = [\n" +
  defs
    .map(
      (d) =>
        "  { id: " +
        JSON.stringify(d.id) +
        ", anchor: " +
        JSON.stringify(d.anchor) +
        ", footprint: " +
        JSON.stringify(d.footprint) +
        ", rotating: " +
        JSON.stringify(d.rotating) +
        ", family: " +
        JSON.stringify(d.family) +
        ", svg: " +
        JSON.stringify(d.svg) +
        " },"
    )
    .join("\n") +
  "\n];\n\n" +
  "export const ASSET_IDS = new Set(ASSETS.map((a) => a.id));\n";

writeFileSync(outTs, body);
console.log(`wrote ${outTs} with ${defs.length} assets`);
